import * as Immutable from 'immutable';
import { createDividerItem, getDividerId, isDividerItem, sanitizeDividerLabel } from './dividers';
import { StationDockImmutable } from './types';

/**
 * -------------
 * - PERSISTED -
 * -------------
 */

// Actions
export const ADD_APP_ITEM = 'browserX/dock/ADD_APP_ITEM';
export type ADD_APP_ITEM = 'browserX/dock/ADD_APP_ITEM';
export const REMOVE_APP_ITEM = 'browserX/dock/REMOVE_APP_ITEM';
export type REMOVE_APP_ITEM = 'browserX/dock/REMOVE_APP_ITEM';
export const CHANGE_APP_ITEM_POSITION = 'browserX/dock/CHANGE_APP_ITEM_POSITION';
export type CHANGE_APP_ITEM_POSITION = 'browserX/dock/CHANGE_APP_ITEM_POSITION';
export const ADD_DIVIDER = 'browserX/dock/ADD_DIVIDER';
export type ADD_DIVIDER = 'browserX/dock/ADD_DIVIDER';
export const RENAME_DIVIDER = 'browserX/dock/RENAME_DIVIDER';
export type RENAME_DIVIDER = 'browserX/dock/RENAME_DIVIDER';
export const REMOVE_DIVIDER = 'browserX/dock/REMOVE_DIVIDER';
export type REMOVE_DIVIDER = 'browserX/dock/REMOVE_DIVIDER';

// Actions Types
export type addAppItem = { type: ADD_APP_ITEM, applicationId: string };
export type removeAppItem = { type: REMOVE_APP_ITEM, applicationId: string };
export type changeAppItemPosition = { type: CHANGE_APP_ITEM_POSITION, applicationId: string, index: number };
// `afterItem` is the dock entry (app id or divider item) to insert after; appended when absent/unknown
export type addDivider = { type: ADD_DIVIDER, dividerId: string, afterItem?: string, label?: string };
export type renameDivider = { type: RENAME_DIVIDER, dividerId: string, label: string };
export type removeDivider = { type: REMOVE_DIVIDER, dividerId: string };
export type DockActions =
  addAppItem
  | removeAppItem
  | changeAppItemPosition
  | addDivider
  | renameDivider
  | removeDivider;

// Action creators
export const addAppItem = (applicationId: string) => ({
  type: ADD_APP_ITEM,
  applicationId,
});
export const removeAppItem = (applicationId: string) => ({
  type: REMOVE_APP_ITEM,
  applicationId,
});
export const changeAppItemPosition = (applicationId: string, index: number) => ({
  type: CHANGE_APP_ITEM_POSITION,
  applicationId,
  index,
});

// `dividerId` is generated by the caller so the action stays deterministic
export const addDivider = (dividerId: string, afterItem?: string, label?: string): addDivider => ({
  type: ADD_DIVIDER,
  dividerId,
  afterItem,
  label,
});
export const renameDivider = (dividerId: string, label: string): renameDivider => ({
  type: RENAME_DIVIDER,
  dividerId,
  label,
});
export const removeDivider = (dividerId: string): removeDivider => ({
  type: REMOVE_DIVIDER,
  dividerId,
});

const findDividerIndex = (state: StationDockImmutable, dividerId: string) =>
  state.findIndex((item: string) => isDividerItem(item) && getDividerId(item) === dividerId);

// Reducer
export default function reducer(state: StationDockImmutable = Immutable.List() as any, action: DockActions): StationDockImmutable {
  switch (action.type) {
    case ADD_APP_ITEM:
      return state.includes(action.applicationId) ?
        state :
        state.push(action.applicationId) as StationDockImmutable;

    case REMOVE_APP_ITEM: {
      const index = state.indexOf(action.applicationId);
      if (index !== -1) {
        return state.remove(index);
      }
      return state;
    }

    case CHANGE_APP_ITEM_POSITION: {
      const currentIndex = state.indexOf(action.applicationId);
      if (currentIndex === -1) return state;
      return state
        .remove(currentIndex)
        .insert(action.index, action.applicationId) as StationDockImmutable;
    }

    case ADD_DIVIDER: {
      if (findDividerIndex(state, action.dividerId) !== -1) return state;
      const item = createDividerItem(action.dividerId, action.label);
      const afterIndex = action.afterItem ? state.indexOf(action.afterItem) : -1;
      return (afterIndex === -1 ? state.push(item) : state.insert(afterIndex + 1, item)) as StationDockImmutable;
    }

    case RENAME_DIVIDER: {
      const index = findDividerIndex(state, action.dividerId);
      if (index === -1) return state;
      const item = createDividerItem(action.dividerId, sanitizeDividerLabel(action.label));
      return state.get(index) === item ? state : state.set(index, item) as StationDockImmutable;
    }

    case REMOVE_DIVIDER: {
      const index = findDividerIndex(state, action.dividerId);
      return index === -1 ? state : state.remove(index);
    }

    default:
      return state;
  }
}
